const getRequirementConfirmation = (order, requirementId) => {
  const confirmations = getVehicleConfirmations(order).filter(
    (confirmation) => confirmation.requirementId === requirementId,
  );
  if (!confirmations.length) {
    return null;
  }
  return (
    confirmations.find((confirmation) => confirmation.status === "Approved") ||
    confirmations.find((confirmation) => confirmation.status === "Rejected") ||
    confirmations[confirmations.length - 1]
  );
};
const getApprovedQuantityForRequirement = (order, requirementId) => {
  const quotations = getRequirementQuotations(order, requirementId);
  const confirmations = getVehicleConfirmations(order).filter(
    (confirmation) =>
      confirmation.requirementId === requirementId &&
      confirmation.status === "Approved",
  );
  return confirmations.reduce((total, confirmation) => {
    const quotation = quotations.find(
      (item) => item.quotationId === confirmation.quotationId,
    );
    return total + Math.max(1, getTrafficQuantity(order, quotation));
  }, 0);
};
/* =========================================================
   REQUIREMENT STATUS
   Quotation Pending:
   No quotations exist.
   Approval Pending:
   Traffic quotation exists but management has not
   approved/rejected it yet.
   Approved:
   Management approved a quotation.
   Rejected:
   Management rejected the quotation.
========================================================= */
const getRequirementStatus = (order, requirementId) => {
  const pendingReplacement = getPendingTransportReplacementForRequirement(
    order,
    requirementId,
  );
  if (pendingReplacement) {
    return "Replacement Pending";
  }
  const quotations = getRequirementQuotations(order, requirementId);
  if (!quotations.length) {
    return "Quotation Pending";
  }
  const requirement = getVehicleRequirements(order).find(
    (item) => item.requirementId === requirementId,
  );
  const requiredQuantity = Math.max(1, Number(requirement?.quantity) || 1);
  const approvedQuantity = getApprovedQuantityForRequirement(
    order,
    requirementId,
  );
  if (approvedQuantity >= requiredQuantity) {
    return "Approved";
  }
  const confirmations = getVehicleConfirmations(order).filter(
    (confirmation) => confirmation.requirementId === requirementId,
  );
  if (
    approvedQuantity === 0 &&
    confirmations.length > 0 &&
    confirmations.every((confirmation) => confirmation.status === "Rejected")
  ) {
    return "Rejected";
  }
  return "Approval Pending";
};
const getOrderQuotationStatus = (order) => {
  const requirements = getVehicleRequirements(order);
  if (!requirements.length) {
    return "Quotation Pending";
  }
  const statuses = requirements.map((requirement) =>
    getRequirementStatus(order, requirement.requirementId),
  );
  if (statuses.some((status) => status === "Replacement Pending")) {
    return "Replacement Pending";
  }
  if (statuses.every((status) => status === "Approved")) {
    return "Approved";
  }
  if (statuses.some((status) => status === "Rejected")) {
    return "Rejected";
  }
  if (statuses.some((status) => status === "Quotation Pending")) {
    return "Quotation Pending";
  }
  return "Approval Pending";
};

      setOrders((previous) =>
        previous.map((order) =>
          order._id === savedOrder._id ? savedOrder : order,
        ),
      );
      loadRequirementForms(savedOrder);
      const text =
        "Transport quotations submitted successfully for management approval.";
      setMessage(text);
      showToast(text, "success");
